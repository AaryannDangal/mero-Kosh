export type DictKey = keyof typeof dict;

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: DictKey | string) => string;
}

const Ctx = createContext<I18nCtx>({ lang: 'en', setLang: () => {}, t: (k) => String(k) });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem('dhukuti.lang') as Lang) || 'en');
  setFormatLang(lang);
  useEffect(() => {
    localStorage.setItem('dhukuti.lang', lang);
    document.documentElement.lang = lang === 'ne' ? 'ne' : 'en';
  }, [lang]);
  const t = (key: string) => {
    const entry = (dict as Record<string, readonly [string, string]>)[key];
    if (!entry) return key;
    return lang === 'ne' ? entry[1] : entry[0];
  };
  return <Ctx.Provider value={{ lang, setLang: setLangState, t }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
